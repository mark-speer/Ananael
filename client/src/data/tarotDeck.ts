/** Fisher–Yates shuffle returning a new array. */
export const shuffleDeck = <T,>(deck: T[]): T[] => {
  const copy = [...deck];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
};
